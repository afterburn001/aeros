// Generates labeled SVG placeholders in Graphics/_placeholders/ and the slot list Graphics/SLOTS.md.
// Run: npm run placeholders   (safe to re-run; never touches your real art in Graphics/)
const fs = require('fs');
const path = require('path');
const G = require('../src/renderer/graphics-slots');

const GRAPHICS = path.join(__dirname, '..', 'Graphics');
const OUT = path.join(GRAPHICS, '_placeholders');

const SKY_COLORS = {
  clear: ['#3d86d6', '#a9d5f7'],
  partly_cloudy: ['#4f86bf', '#c0d4e6'],
  cloudy: ['#6f7c8c', '#b6bfca'],
  fog: ['#8f99a3', '#d6dade'],
  rain: ['#3e4f66', '#7b8ca2'],
  snow: ['#94a7bb', '#e6edf4'],
  storm: ['#262c38', '#555d6e'],
};
const SEASON_COLORS = { spring: '#6fcf6f', summer: '#f2c94c', fall: '#e07b39', winter: '#d8ecff' };
const CONDITION_COLORS = {
  clear: '#f2b134', partly_cloudy: '#8fb3d9', cloudy: '#8a96a3', fog: '#a7b0b8', drizzle: '#6f9fcf',
  rain: '#3f78b5', freezing_rain: '#7fc3d9', snow: '#cfe3f5', thunderstorm: '#5b4f8c', unknown: '#777777',
};
const UI_GLYPHS = {
  search: '⌕', settings: '⚙', close: '✕', wind: '≋', humidity: '%', sunrise: '↑', sunset: '↓', home: '⌂', location: '◎',
};

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Darken a hex color toward deep navy for night variants.
function night(hex, amount = 0.72) {
  const n = parseInt(hex.slice(1), 16);
  const mix = (c, t) => Math.round(c + (t - c) * amount);
  const r = mix(n >> 16, 0x08), g = mix((n >> 8) & 255, 0x10), b = mix(n & 255, 0x26);
  return `#${((r << 16) | (g << 8) | b).toString(16).padStart(6, '0')}`;
}

function backdropSvg({ slot, season, time, sky }) {
  let [top, bottom] = SKY_COLORS[sky];
  if (time === 'night') [top, bottom] = [night(top), night(bottom, 0.6)];
  const band = season ? SEASON_COLORS[season] : '#888888';
  const title = season ? `${season.toUpperCase()} · ${time.toUpperCase()} · ${sky.replace('_', ' ').toUpperCase()}` : 'DEFAULT BACKDROP';
  // Label repeated down the image so it peeks out between the UI cards.
  const labels = [150, 420, 690, 900].map((y) => `
  <text x="270" y="${y}" text-anchor="middle" font-family="Segoe UI, sans-serif" font-size="30" font-weight="700" fill="#ffffff" fill-opacity="0.35">${xml(title)}</text>
  <text x="270" y="${y + 30}" text-anchor="middle" font-family="Consolas, monospace" font-size="18" fill="#ffffff" fill-opacity="0.35">${xml(slot)}</text>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="540" height="960" viewBox="0 0 540 960">
  <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${top}"/><stop offset="1" stop-color="${bottom}"/></linearGradient></defs>
  <rect width="540" height="960" fill="url(#g)"/>
  <rect y="930" width="540" height="30" fill="${band}" fill-opacity="0.8"/>
  <text x="270" y="951" text-anchor="middle" font-family="Segoe UI, sans-serif" font-size="16" font-weight="700" fill="#000" fill-opacity="0.7">PLACEHOLDER · ${xml(season || 'any season')}</text>${labels}
</svg>
`;
}

function iconSvg({ slot, condition, time }) {
  let color = CONDITION_COLORS[condition];
  if (time === 'night') color = night(color, 0.5);
  const lines = [...condition.toUpperCase().split('_'), ...(time ? [time.toUpperCase()] : [])];
  const startY = 64 - ((lines.length - 1) * 18) / 2 + 6;
  const text = lines.map((l, i) => `<text x="64" y="${startY + i * 18}" text-anchor="middle" font-family="Segoe UI, sans-serif" font-size="16" font-weight="700" fill="#fff">${xml(l)}</text>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
  <!-- placeholder: ${slot} -->
  <rect x="4" y="4" width="120" height="120" rx="22" fill="${color}" stroke="#fff" stroke-opacity="0.6" stroke-width="3" stroke-dasharray="8 6"/>
  ${text}
</svg>
`;
}

function uiSvg({ slot, name }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">
  <!-- placeholder: ${slot} -->
  <text x="32" y="46" text-anchor="middle" font-family="Segoe UI Symbol, Segoe UI, sans-serif" font-size="42" fill="#fff">${xml(UI_GLYPHS[name] || '?')}</text>
</svg>
`;
}

function slotsDoc(slots) {
  const list = (kind) => slots.filter((s) => s.kind === kind).map((s) => `- \`${s.slot}\``).join('\n');
  return `# Graphics slots

Generated by \`npm run placeholders\`. Do not edit by hand.

## What the app uses today

| Art | Where it goes | How it's chosen |
| --- | --- | --- |
| Skins (full-window backgrounds) | \`Graphics/skin_*.png\` or \`.jpg\` | Live weather + day/night via \`src/skins-map.js\`, or picked in Settings |
| Weather icons | \`Graphics/icons/icon_*.png\` | Panel condition + day/night via \`src/icons-map.js\` |
| Wordmark | \`Graphics/aeros_wordmark.png\` | \`WORDMARK_FILE\` in \`src/config.js\` |
| UI icons | \`Graphics/ui_*.png\` | By slot name, listed below |

Your PNG masters are never changed. The app renders copies it caches in \`Graphics/_cache/\`, rebuilt
when a master is newer. That folder is safe to delete. To force a rebuild after restoring an older
file, delete it and relaunch.

## Skins
- Portrait, about 9:16 (shown cropped to fill). PNG masters render from a quality-85 JPG copy.
- Any \`skin_*\` file is found on next launch and listed in Settings > Skin
  (\`skin_night_partly_cloudy\` shows as "Partly cloudy night").
- For a new name to show on live weather, add it to \`src/skins-map.js\`.

## Weather icons
- Square PNG on solid black (1024×1024 works well). Don't remove the black yourself: the app knocks it
  out to transparent, keeping dark areas that are enclosed by bright edges.
- Copies are downscaled to the exact screen size and sharpened.
- Any \`icon_*.png\` is found on next launch. For a new name to be used, add it to \`src/icons-map.js\`.
- The now tile and hourly row use day/night for their own time. Forecast cards use the day icon.

## Placeholders and older slots
Everything below is a labeled stand-in in \`_placeholders\`, or a slot name you can fill with art
(PNG recommended; WEBP, JPG, GIF, SVG also work) in this \`Graphics\` folder, not in \`_placeholders\`.
Your file always beats the placeholder.

- **UI icons** are still in use. Show at 18px (make them 64×64, white on transparent).
- **Backdrops** show only when there are no skin files, or \`USE_SKIN\` is false in \`src/config.js\`.
  Shown portrait and cropped to fill (~540×960 or larger).
- **Weather icon slots** show only when \`Graphics/icons/\` has no usable \`icon_*.png\`. They have
  different names from the real set above.

The app tries names from most specific to least specific and uses the first real file it finds:

- Backdrop: \`backdrop_<season>_<day|night>_<sky>\` → \`backdrop_<day|night>_<sky>\` → \`backdrop_<sky>\` → \`backdrop_default\`
- Weather icon slot: \`icon_<condition>_<day|night>\` → \`icon_<condition>\` → \`icon_unknown\`

Seasons: ${G.SEASONS.join(', ')} (Mar–May, Jun–Aug, Sep–Nov, Dec–Feb)
Skies: ${G.SKIES.join(', ')}
Icon conditions: ${G.CONDITIONS.join(', ')}

## UI icons
${list('ui')}

## Backdrops (only without skins)
${list('backdrop')}

## Weather icon slots (only without Graphics/icons/)
${list('icon')}
`;
}

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const slots = G.placeholderSlots();
  for (const s of slots) {
    const svg = s.kind === 'backdrop' ? backdropSvg(s) : s.kind === 'icon' ? iconSvg(s) : uiSvg(s);
    fs.writeFileSync(path.join(OUT, `${s.slot}.svg`), svg);
  }
  fs.writeFileSync(path.join(GRAPHICS, 'SLOTS.md'), slotsDoc(slots));
  console.log(`Wrote ${slots.length} placeholders to ${path.relative(process.cwd(), OUT)} and Graphics/SLOTS.md`);
}

main();
